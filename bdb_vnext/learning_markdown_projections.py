def write_projection_file_atomic(target_path: Path | str, content: str) -> None:
    """Atomically write content to target path using a temporary file in the same directory."""
    path = Path(target_path).resolve()
    path.parent.mkdir(parents=True, exist_ok=True)

    # Create temporary file in same parent directory to guarantee same filesystem for atomic rename
    tmp_fd, tmp_file = tempfile.mkstemp(prefix=".tmp_proj_", dir=str(path.parent), text=True)
    try:
        with os.fdopen(tmp_fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        # Atomic replace with bounded retry for Windows concurrent handle collisions
        last_err: Exception | None = None
        for attempt in range(25):
            try:
                os.replace(tmp_file, str(path))
                last_err = None
                break
            except (PermissionError, OSError) as exc:
                last_err = exc
                time.sleep(0.01 * (attempt + 1))
        if last_err is not None:
            raise last_err
    except Exception:
        if os.path.exists(tmp_file):
            try:
                os.remove(tmp_file)
            except OSError:
                pass
        raise


